export const ADDITIONAL_VOCABULARY: VocabWord[] = topics.flatMap(({ category, entries }) => {
  const categoryId = category.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
  return entries.map(([english, phonetic, translation, partOfSpeech, exampleSentence, exampleTranslation], index) => ({
    id: `extra_${categoryId}_${index + 1}`,
    english,
    phonetic,
    translation,
    category,
    partOfSpeech,
    exampleSentence,
    exampleTranslation,
  }));
});
